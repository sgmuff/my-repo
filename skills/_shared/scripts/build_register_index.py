#!/usr/bin/env python3
"""Rebuild a register index from entry metadata.

Usage: python3 build_register_index.py <register-folder> <ropa|ai-system>

Reads the YAML metadata block at the top of every *.md file in the folder
(except index.md) whose `type` matches, and rewrites index.md. Uses only the
standard library and handles the flat key: value metadata the entry
templates use.
"""
import datetime
import os
import re
import sys

REGISTERS = {
    "ropa": {
        "heading": "Record of processing activities: index",
        "columns": [
            ("id", "ID"), ("title", "Activity"), ("record_type", "Record type"),
            ("requesting_business_area", "Business area"), ("status", "Status"),
            ("lawful_basis_status", "Lawful basis"), ("special_category", "Special category"),
            ("children_or_students", "Children or students"), ("restricted_transfers", "Restricted transfers"),
            ("sale_or_sharing", "Sale or sharing"), ("ai_used", "AI"), ("assessment", "Assessment"),
            ("required_fields_tbc", "TBC fields"), ("next_review", "Next review"),
        ],
    },
    "ai-system": {
        "heading": "AI system and agent inventory: index",
        "columns": [
            ("id", "ID"), ("title", "System or agent"), ("source", "Source"),
            ("requesting_business_area", "Business area"), ("status", "Status"),
            ("tier", "Tier"), ("eu_ai_act_category", "EU AI Act"), ("autonomy", "Autonomy"),
            ("decisions_about_people", "Decisions about people"), ("personal_data", "Personal data"),
            ("aiuc_1_mode", "AIUC-1"), ("follow_ons", "Follow-ons"),
            ("required_fields_tbc", "TBC fields"), ("next_review", "Next review"),
        ],
    },
}


def read_metadata(path):
    with open(path, encoding="utf-8") as f:
        text = f.read()
    m = re.match(r"---\n(.*?)\n---", text, re.S)
    if not m:
        return None
    meta = {}
    for line in m.group(1).splitlines():
        if not line or line.startswith((" ", "\t", "-", "#")):
            continue
        key, sep, value = line.partition(":")
        if not sep:
            continue
        value = re.sub(r"\s+#.*$", "", value).strip().strip('"').strip("'")
        meta[key.strip()] = value
    return meta


def cell(value):
    return (value or "").replace("|", "\\|")


def main(folder, kind):
    if not os.path.isdir(folder):
        sys.exit(f"Not a folder: {folder}")
    if kind not in REGISTERS:
        sys.exit(f"Unknown register type: {kind}. Use: {', '.join(REGISTERS)}")
    COLUMNS = REGISTERS[kind]["columns"]
    rows, skipped = [], []
    for name in sorted(os.listdir(folder)):
        if not name.endswith(".md") or name == "index.md":
            continue
        path = os.path.join(folder, name)
        meta = read_metadata(path)
        if not meta or meta.get("type") != kind:
            skipped.append(name)
            continue
        meta["title"] = f"[{meta.get('title', name)}]({name})"
        rows.append(meta)
    rows.sort(key=lambda r: r.get("id", ""))

    today = datetime.date.today().isoformat()
    approved = sum(1 for r in rows if r.get("status", "").lower().startswith("approved"))
    tbc = 0
    for r in rows:
        try:
            tbc += int(r.get("required_fields_tbc", "0"))
        except ValueError:
            pass
    overdue = [r.get("id", "") for r in rows if r.get("next_review", "9999") < today]

    lines = [
        "# " + REGISTERS[kind]["heading"],
        "",
        "Generated by `_shared/scripts/build_register_index.py` from each entry's metadata. "
        "Don't edit by hand; edit the entries and rebuild.",
        "",
        f"Last built: {today} · Entries: {len(rows)} · Approved: {approved} · Required fields TBC: {tbc}",
        "",
    ]
    if overdue:
        lines += [f"> **Blocker:** Review overdue for {', '.join(overdue)}.", ""]
    lines.append("| " + " | ".join(label for _, label in COLUMNS) + " |")
    lines.append("|" + "---|" * len(COLUMNS))
    for r in rows:
        lines.append("| " + " | ".join(cell(r.get(key)) for key, _ in COLUMNS) + " |")
    if skipped:
        lines += ["", f"Files skipped (no {kind} metadata): " + ", ".join(skipped)]
    with open(os.path.join(folder, "index.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"index.md rebuilt: {len(rows)} entries, {tbc} required fields TBC, {len(overdue)} overdue, {len(skipped)} skipped")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
