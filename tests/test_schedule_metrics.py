import pytest

from gov.cli import main
from gov.render import render_tree


def test_schedule_needs_an_as_of_date(ropa_root):
    with pytest.raises(SystemExit):
        main(["--root", str(ropa_root), "schedule", str(ropa_root / "compliance")])


def test_schedule_flags_against_the_given_date(ropa_root, capsys):
    render_tree(ropa_root)
    out = ropa_root / "compliance"
    assert main(["--root", str(ropa_root), "schedule", str(out), "--as-of", "2027-09-01"]) == 0
    text = (out / "schedule.md").read_text()
    assert "Built 2027-09-01" in text and "| 2027-10-18 | Due soon | ROPA-0001 |" in text
    assert main(["--root", str(ropa_root), "schedule", str(out), "--as-of", "2027-11-01"]) == 0
    assert "| 2027-10-18 | Overdue | ROPA-0001 |" in (out / "schedule.md").read_text()


def test_metrics_need_an_as_of_date_and_name_it(ropa_root):
    render_tree(ropa_root)
    out = ropa_root / "compliance"
    with pytest.raises(SystemExit):
        main(["--root", str(ropa_root), "metrics", str(out)])
    assert main(["--root", str(ropa_root), "metrics", str(out), "--as-of", "2026-12-31"]) == 0
    report = (out / "reports" / "metrics-2026-12-31.md").read_text()
    assert "Generated by `gov metrics`" in report and "2026-10-02 to 2026-12-31" in report


def test_deadlines_run_through_gov(capsys, root):
    assert main(["--root", str(root), "deadlines", "2026-10-21", "fadp"]) == 0
    assert "2026-11-20" in capsys.readouterr().out
