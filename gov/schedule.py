"""Build the compliance schedule from deliverable metadata.

Usage:
  gov schedule <output-root> --as-of YYYY-MM-DD [--window 60]

--as-of is required: gov never reads the clock, so the same files and date give the same schedule.

Scans every *.md file under the output root (default compliance/) for the
metadata keys next_review, next_test, earliest_deadline, and due, and every
gov record (*.yaml) for its open actions' due dates and, in readiness reports,
the testing schedule's next due dates. It writes
<output-root>/schedule.md: one table sorted by date, with overdue items and
items due within the window flagged. Recurring duties (AIUC-1 quarterly
testing, annual reviews) show up through each control's or document's own
next_test or next_review date, so the schedule stays a list of actions, not
calendar events.
"""
import argparse
import datetime as dt
import os
import re
import sys

KEYS = ("next_review", "next_test", "earliest_deadline", "due")
DATE = re.compile(r"(\d{4}-\d{2}-\d{2})")


def meta(path):
    try:
        text = open(path, encoding="utf-8").read()
    except (OSError, UnicodeDecodeError):
        return None
    m = re.match(r"---\n(.*?)\n---", text, re.S)
    if not m:
        return None
    out = {}
    for line in m.group(1).splitlines():
        if not line or line[0] in " \t-#":
            continue
        k, sep, v = line.partition(":")
        if sep:
            out[k.strip()] = re.sub(r"\s+#.*$", "", v).strip()
    return out


def record_items(path):
    """(date, what, title) rows from a gov record: open actions with a due date, and readiness testing rows."""
    import yaml
    try:
        data = yaml.safe_load(open(path, encoding="utf-8"))
    except (OSError, UnicodeDecodeError, yaml.YAMLError):
        return None, []
    if not isinstance(data, dict) or "id" not in data or "type" not in data:
        return None, []
    rows = []
    for a in data.get("actions") or []:
        d = DATE.fullmatch(str(a.get("due", "")))
        if d and a.get("status") == "open":
            rows.append((d.group(1), f"action {a['id']}", a["action"]))
    for q in data.get("open_questions") or []:
        d = DATE.fullmatch(str(q.get("needed_by", "")))
        if d:
            rows.append((d.group(1), f"question {q['id']}", q["question"]))
    for e in data.get("evidence") or [] if data["type"] == "ctl" else []:
        d = DATE.fullmatch(str(e.get("stale_after", "")))
        if d:
            rows.append((d.group(1), "evidence stale", f"{e['id']}: {e['what']}"))
    for t in data.get("testing") or [] if data["type"] == "rdy" else []:
        d = DATE.fullmatch(str(t.get("next_due", "")))
        if d:
            rows.append((d.group(1), "next test", f"{t['duty']} ({t['requirement']})"))
    return data, rows


def main(argv=None):
    ap = argparse.ArgumentParser(prog="gov schedule", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("root")
    ap.add_argument("--as-of", required=True, help="YYYY-MM-DD: the date items are flagged against")
    ap.add_argument("--window", type=int, default=60)
    a = ap.parse_args(argv)
    if not os.path.isdir(a.root):
        sys.exit(f"Not a folder: {a.root}")
    today = dt.date.fromisoformat(a.as_of)
    horizon = today + dt.timedelta(days=a.window)
    items = []
    for dirpath, _, names in os.walk(a.root):
        for n in names:
            if n.endswith(".yaml") and ".gov" not in dirpath.split(os.sep):
                data, rows = record_items(os.path.join(dirpath, n))
                rel = os.path.relpath(os.path.join(dirpath, n[:-5] + ".md"), a.root)
                for d, what, title in rows:
                    date = dt.date.fromisoformat(d)
                    status = "Overdue" if date < today else ("Due soon" if date <= horizon else "")
                    items.append((date, status, str(data["id"]), data["type"], what, title, rel))
                continue
            if not n.endswith(".md") or n in ("index.md", "schedule.md") or n.endswith(("-notices.md", "-drafts.md")):
                continue
            p = os.path.join(dirpath, n)
            md = meta(p)
            if not md:
                continue
            for k in KEYS:
                v = md.get(k, "")
                d = DATE.search(v)
                if not d:
                    continue
                date = dt.date.fromisoformat(d.group(1))
                status = "Overdue" if date < today else ("Due soon" if date <= horizon else "")
                rel = os.path.relpath(p, a.root)
                items.append((date, status, md.get("id", n), md.get("type", ""), k.replace("_", " "), md.get("title", n), rel))
    items.sort()
    lines = [
        "# Compliance schedule",
        "",
        "Generated by `gov schedule` from each deliverable's metadata. "
        "Don't edit by hand; update the deliverables and rebuild. These are actions, not calendar events.",
        "",
        f"Built {today.isoformat()} · Items: {len(items)} · Overdue: {sum(1 for i in items if i[1] == 'Overdue')} · "
        f"Due within {a.window} days: {sum(1 for i in items if i[1] == 'Due soon')}",
        "",
        "| Date | Flag | ID | Type | What | Title | File |",
        "|---|---|---|---|---|---|---|",
    ]
    for date, status, i, t, what, title, rel in items:
        lines.append(f"| {date.isoformat()} | {status} | {i} | {t} | {what} | {title.replace('|', '/')} | [{rel}]({rel}) |")
    with open(os.path.join(a.root, "schedule.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"schedule.md: {len(items)} items, {sum(1 for i in items if i[1] == 'Overdue')} overdue")

